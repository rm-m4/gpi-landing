def region(data, logos):
    tabs = [dict(t, cards=t["cards"][:PER_TAB]) for t in data["tabs"]]
    buttons, panels = U.listing(tabs, logos)
    # bond-utsav.html shows a struck-through "old yield" on some cards that it marks DUMMY (not captured);
    # on regulated content a made-up figure is out (taste-skill: no fake numbers), so this page leaves it off.
    panels, n = re.subn(r'\n\s*<s class="gp-ucard__was">.*?</s> <!-- DUMMY: old yield, not captured -->', "", panels)
    # no marketing lines on this page's cards (user, 2026-10-14)
    panels = re.sub(r'\n\s*<p class="gp-ucard__note">.*?</p>', "", panels, flags=re.S)
    return f'''{START}
  <!-- GENERATED by pages/_utsav6.py: bond-utsav.html's categories (crawl/rendered/bond-utsav.tabs.json,
       captured {data["captured"][:10]}), at most {PER_TAB} bonds a category, in this page's theme. Edit the generator. -->
  <section class="bu3-sec bu6-list gp-utsav-listing gp-utsav-listing--pills" aria-labelledby="utsav-heading">
    <div class="bu3-shell">
      <div class="gp-section__head gp-utsav-head">
        <h2 id="utsav-heading" class="bu3-h2">Select A Category</h2>
        <!-- COPY: 14% (user, 2026-10-14); bond-utsav.html's capture says 13.8%. -->
        <p class="gp-section__sub">Invest in Senior Secured Bonds and earn returns up to <span class="gp-hero__figure">14% p.a.</span></p>
      </div>

      <div>
        <div class="gp-pills">
          <div class="gp-pills__track" role="tablist" aria-label="Select A Category">
{buttons}
          </div>
        </div>

        {panels}
      </div>
    </div>
  </section>
  {END}'''


def main():
    data = json.load(open(os.path.join(ROOT, "crawl", "rendered", "bond-utsav.tabs.json"), encoding="utf-8"))
    logos = U.logo_names(data["tabs"])
    page = open(PAGE, encoding="utf-8").read()
    if START not in page:
        raise SystemExit("bond-utsav6.html: no %s region" % START)
    i, j = page.index(START), page.index(END) + len(END)
    page = page[:i] + region(data, logos) + page[j:]
    # styles and scripts, once
    page = re.sub(r"<style>\n/\* bond-utsav6's listing \(pages/_utsav6.py\).*?</style>\n", "", page, flags=re.S)
    page = page.replace("</head>", STYLE + "</head>", 1)
    page = re.sub(r"<script>\n// UTSAV6:TABS.*?</script>\n", "", page, flags=re.S)
    js = open(os.path.join(HERE, "_tabs.js"), encoding="utf-8").read()
    k = page.rindex("</body>")
    page = page[:k] + "<script>\n// UTSAV6:TABS (pages/_utsav6.py): the category tablist and pill scrolling, as on bond-utsav.html\n" + js + U.SCROLL_JS + "</script>\n" + page[k:]
    # the pre-login final footer (user, 2026-10-14): footer-ggn-prelogin-home, put in by _build's own helper
    B.GGN["bond-utsav6.html"] = "footer-ggn-prelogin-home.html"
    page = B.ggn_footer("bond-utsav6.html", page)
    open(PAGE, "w", encoding="utf-8").write(page)
    print("bond-utsav6.html: %d categories, at most %d bonds each" % (len(data["tabs"]), PER_TAB))


if __name__ == "__main__":
    main()
