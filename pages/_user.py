def shell(title, desc, current):
    """Head, promo bar and logged-in header / footer and scripts, from the
    generated corporate-bonds.html."""
    with open(os.path.join(HERE, "corporate-bonds.html"), encoding="utf-8") as f:
        src = f.read()
    top = src[:src.index('<main id="main-content">')]
    bottom = src[src.index("</main>"):]

    top = re.sub(r"<title>.*?</title>", "<title>%s</title>" % title, top, count=1, flags=re.S)
    top = re.sub(r'<meta name="description" content="[^"]*">',
                 '<meta name="description" content="%s">' % desc, top, count=1)
    top = top.replace('<link rel="stylesheet" href="../assets/final.css">',
                      '<link rel="stylesheet" href="../assets/final.css">\n'
                      '<link rel="stylesheet" href="../assets/user.css">', 1)
    top = top.replace("</title>", "</title>\n<!-- Post-login page, generated by pages/_user.py "
                      "from the goldenpi.com capture of 2026-09-26. -->", 1)

    # Logged in: home is the explore page, and the nav points at the user pages.
    top = top.replace('<a href="index.html" class="flex-none">',
                      '<a href="user-explore.html" class="flex-none">', 1)
    top = top.replace(' aria-current="page"', "")
    top = top.replace("header-nav-bonds-selected.svg", "header-nav-bonds.svg")
    top = top.replace('href="corporate-bonds.html"', 'href="user-corporate-bonds.html"')
    top = top.replace('href="fixed-deposits.html"', 'href="user-fixed-deposits.html"')
    if current == "bonds":
        top = top.replace('href="user-corporate-bonds.html">\n        <img src="../assets/img/header-nav-bonds.svg"',
                          'href="user-corporate-bonds.html" aria-current="page">\n'
                          '        <img src="../assets/img/header-nav-bonds-selected.svg"', 1)
    if current == "fd":
        top = top.replace('href="user-fixed-deposits.html">\n        <img src="../assets/img/header-nav-fd.svg"',
                          'href="user-fixed-deposits.html" aria-current="page">\n'
                          '        <img src="../assets/img/header-nav-fd-selected.svg"', 1)

    # Login becomes the bell and the account avatar, both controls, not links,
    # as on the live site.
    login = re.search(r'    <button type="button" class="gp-cta gp-cta--primary gp-cta--sm flex-none ml-auto lg:ml-0">'
                      r".*?</button>\n", top, re.S)
    if not login:
        raise SystemExit("login button not found in corporate-bonds.html")
    top = top[:login.start()] + (
        '    <div class="gp-user flex-none ml-auto lg:ml-0">\n'
        '      <button type="button" class="gp-user__bell" aria-label="Notifications">\n'
        '        <img src="../assets/img/notify-bell.svg" alt="" width="20" height="20">\n'
        '      </button>\n'
        '      <!-- DATA: the account holder\'s initials. -->\n'
        '      <button type="button" class="gp-user__avatar" aria-label="Account menu">IN</button>\n'
        '    </div>\n') + top[login.end():]
    return top + '<main id="main-content">\n', "\n" + bottom


def section(banner, inner, id_=None, cls="gp-section gp-section--tight gp-section--flush-top"):
    rule = "=" * max(4, 66 - len(banner))
    return ('  <!-- %s %s -->\n  <section data-reveal class="%s"%s>\n    <div class="gp-shell">\n'
            '%s\n    </div>\n  </section>\n' % (rule, banner, cls, ' id="%s"' % id_ if id_ else "", inner))


def head(title, extra=""):
    return ('      <div class="gp-section__head gp-section__head--marked">\n'
            '        <h2 class="gp-section__title">%s</h2>\n%s      </div>\n' % (title, extra))


