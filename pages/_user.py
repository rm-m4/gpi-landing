def md(slug):
    with open(os.path.join(ROOT, "content", "prod_user_%s.md" % slug), encoding="utf-8") as f:
        return f.read()


def rendered(slug):
    with open(os.path.join(ROOT, "crawl", "rendered", "prod_user_%s.html" % slug),
              encoding="utf-8") as f:
        return html.unescape(f.read())


def esc(s):
    return html.escape(s, quote=False)


def local_img(url):
    """Local file for a captured image URL, via assets/img-map.tsv."""
    with open(os.path.join(ROOT, "assets", "img-map.tsv"), encoding="utf-8") as f:
        for row in f:
            u, _, n = row.rstrip("\n").partition("\t")
            if u == url:
                return n
    raise SystemExit("image not in img-map.tsv: %s" % url)


# ------------------------------------------------------------ copy from md

def faqs(slug):
    """[(question, [answer paragraphs])] from the page's FAQ block."""
    text = md(slug)
    block = text[text.index("### Frequently Asked Questions"):text.index("#### Need Help?")]
    out = []
    for part in block.split("\n#### ")[1:]:
        lines = [l for l in part.splitlines() if l.strip()]
        out.append((lines[0], [l[2:] for l in lines[1:] if l.startswith("- ")]))
    return out


def reviews(slug):
    """[(name, quote)] in page order, once each (the carousel repeats them)."""
    text = md(slug)
    start = text.index("\n", text.index("### Trusted by 18 Lac+"))
    block = text[start:text.index("### Your guide to invest smartly")]
    seen, out = set(), []
    for name, quote in re.findall(r"### (.+)\n\n- (.+)", block):
        if name not in seen:
            seen.add(name)
            out.append((name, quote))
    return out


def blogs(slug):
    """[(title, date, thumbnail)]: titles and dates from the md, thumbnails
    from the capture, where they are CSS backgrounds in the same order."""
    text = md(slug)
    block = text[text.index("### Your guide to invest smartly"):].split("\n### ")[0]
    items = [l[2:] for l in block.splitlines() if l.startswith("- ")]
    pairs = list(zip(items[0::2], items[1::2]))
    thumbs = re.findall(r'blog-img-container" style="background-image: url\("([^"]+)"\)',
                        rendered(slug))
    if len(thumbs) < len(pairs):
        raise SystemExit("%s: %d blog thumbnails for %d posts" % (slug, len(thumbs), len(pairs)))
    return [(t, d, local_img(u)) for (t, d), u in zip(pairs, thumbs)]


