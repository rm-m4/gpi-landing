"""Write the blog pages, two directions for each of the two live blog pages:

    blog.html            goldenpi.com/blog, redesigned (the direction we recommend)
    blog-minimal.html    goldenpi.com/blog, their layout moved onto the set's schema
    blog-post.html       one article, redesigned
    blog-post-minimal.html  one article, their layout on the set's schema

Source is production (the blog is WordPress + Soledad, the same on uatnew):
crawl/rendered/prod_blog*.html, read into JSON by crawl/blog_extract.js;
images from crawl/blog_images.sh (JPEG, 640px and 1200px for srcset). Every string, rate,
date and link below comes from those captures; content/prod_blog*.md is the
review copy.

Colour: the set's gold stays the action colour (buttons). The blog's own navy
(#19386d, their header, buttons and footer) is kept as the reading colour:
category labels, links, the summary callout, the contents rail and, on the
redesign, a navy tint over every thumbnail that lifts on hover. Their
thumbnails come from many designers (black-and-gold, white, bright blue);
the tint makes a grid of them read as one set, and it is CSS, so every future
upload gets it with no image editing. CSS is the BLOG block at the end of
final.css.

    python3 pages/_blog.py && python3 pages/_build.py
"""
