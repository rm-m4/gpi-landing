def sidebar(minimal, toc):
    out = []
    if toc and not minimal:
        out.append("""        <nav class="gp-btoc" aria-labelledby="toc-title">
          <p class="gp-btoc__title" id="toc-title">Table of Contents</p>
          <ol>%s</ol>
        </nav>""" % "".join('<li><a href="%s">%s</a></li>' % (esc(x["href"]), esc(x["label"])) for x in toc))
    for w in POST["sidebar"]:
        if w["items"] and "date" in w["items"][0]:
            items = "".join('<li><a href="%s">%s</a><time>%s</time></li>' % (esc(local(i["href"], minimal)), esc(i["title"]), esc(i["date"])) for i in w["items"])
            out.append('        <section class="gp-bwidget"><h2 class="gp-bwidget__title">%s</h2><ul class="gp-bwidget__news" role="list">%s</ul></section>' % (esc(w["title"]), items))
        else:
            items = "".join('<li><a href="%s">%s</a></li>' % (esc(local(i["href"], minimal)), esc(i["title"])) for i in w["items"])
            out.append('        <section class="gp-bwidget"><h2 class="gp-bwidget__title">%s</h2><ul class="gp-bwidget__links" role="list">%s</ul></section>' % (esc(w["title"]), items))
    return "\n".join(out)


