def crumbs(items):
    out = []
    for label, href in items:
        out.append('<a href="%s">%s</a>' % (esc(href), esc(label)) if href else
                   '<span aria-current="page">%s</span>' % esc(label))
    return ('      <nav class="gp-bcrumb" aria-label="Breadcrumb">%s</nav>'
            % '<span aria-hidden="true">&rsaquo;</span>'.join(out))


