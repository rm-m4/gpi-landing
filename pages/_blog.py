def img_base(url):
    """Captured image URL -> local base name, as blog_images.sh wrote it."""
    if url in IMG:
        return IMG[url]
    full = re.sub(r"-\d+x\d+(\.\w+)$", r"\1", url)
    return IMG[full]


def pic(url, alt="", cls="", eager=False, sizes="(min-width: 960px) 380px, 90vw"):
    b = img_base(url)
    return ('<img%s src="../assets/img/blog/%s.jpg" srcset="../assets/img/blog/%s-640.jpg 640w, ../assets/img/blog/%s.jpg 1200w"'
            ' sizes="%s" alt="%s"%s decoding="async">') % (
        ' class="%s"' % cls if cls else "", b, b, b, sizes, esc(alt), "" if eager else ' loading="lazy"')


def local(href, minimal):
    """Point captured links at the pages this repo has; anything else stays live."""
    suffix = "-minimal" if minimal else ""
    h = href.split("?")[0].rstrip("/")
    known = {
        "https://goldenpi.com": "index.html",
        "https://goldenpi.com/corporate-bonds": "corporate-bonds.html",
        "https://goldenpi.com/collections/tax-free-bonds": "collections-tax-free-bonds.html",
        "https://goldenpi.com/bond-utsav": "bond-utsav.html",
        "https://goldenpi.com/blog": "blog%s.html" % suffix,
        POST_URL.rstrip("/"): "blog-post%s.html" % suffix,
    }
    return known.get(h, href)


def person(author):
    """'Rohit Suhag | CA | IIM Calcutta' -> ('Rohit Suhag', 'CA | IIM Calcutta').
    Their bylines use both '|' and ',' after the name."""
    m = re.match(r"^(.*?)\s*[|,]\s*(.*)$", author)
    return (m.group(1), m.group(2)) if m else (author, "")


def page(slug, title, desc, note, body, extra_js=""):
    out = HEAD.format(title=esc(title), desc=esc(desc), note=note, slug="blog", snap=SNAPSHOT)
    out = out.replace("Generated by pages/_prod.py from crawl/rendered/prod_blog.html",
                      "Generated by pages/_blog.py from crawl/rendered/prod_blog*.json")
    out = out.replace("copy in content/prod_blog.md", "copy in content/prod_blog*.md")
    out = out.replace('<body class="gp-prod">', '<body class="gp-prod gp-blog">')
    # Each thumb shows its whole image (their banners are 16:9 and 2.11:1, and
    # carry their titles to the edge), so the box's spare band is filled with
    # the same art, blurred: the small copy, as a background, set here once.
    body = re.sub(r'<span class="gp-bthumb([^"]*)"><img([^>]*?) src="\.\./assets/img/blog/([^"]+)\.jpg"',
                  r'<span class="gp-bthumb\1" style="background-image:url(../assets/img/blog/\3-640.jpg)"><img\2 src="../assets/img/blog/\3.jpg"', body)
    out += SHELL + '<main id="main-content">\n' + body + "\n</main>\n\n" + FOOTER + "\n" + SCRIPTS + extra_js
    out += "\n</body>\n</html>\n"
    open(os.path.join(HERE, slug + ".html"), "w", encoding="utf-8").write(out)
    print("wrote pages/%s.html" % slug)


