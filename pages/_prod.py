def media():
    cards = INTERACT["media"]["cards"]
    groups = {}
    for c in cards:
        title, desc, source = c["texts"]
        year = re.search(r"(\d{4})\s*$", source).group(1)
        groups.setdefault(year, []).append((title, desc, source, c["href"], local(c["img"])))

    def split(src):
        m = re.match(r"^(.*?),\s*(\w+\.? \d{1,2}, \d{4})\s*$", src)
        return (m.group(1).strip(), m.group(2)) if m else (src, "")

    def card(t, d, src, href, img):
        """Their live media card in the set's schema: title, summary and
        "Publication, date" on the left, the story's photo square on the right."""
        pub, when = split(src)
        return """            <a class="gp-presscard" href="%s" target="_blank" rel="noopener">
              <span class="gp-presscard__body">
                <span class="gp-presscard__title">%s</span>
                <span class="gp-presscard__desc">%s</span>
                <span class="gp-presscard__source"><b>%s</b>%s</span>
              </span>
              <span class="gp-presscard__frame"><img src="../assets/img/%s" alt="" width="160" height="160" loading="lazy"></span>
            </a>""" % (esc(href), esc(t), esc(d), esc(pub), (", " + esc(when)) if when else "", img)

    years = sorted(groups, reverse=True)
    body = hero("Media", """          <h1 class="t-h1"><span class="t-bronze">Media Coverage</span></h1>""", "")

    tabs = "\n".join("""            <button type="button" class="gp-tab" role="tab" id="tab-y%s"
                    aria-controls="panel-y%s" aria-selected="%s"%s>%s</button>""" % (
        y, y, "true" if n == 0 else "false", "" if n == 0 else ' tabindex="-1"', y) for n, y in enumerate(years))
    panels = []
    for n, y in enumerate(years):
        items = groups[y]
        # Nine fill three rows of three; a short year shows the most it can
        # without leaving a row part-empty. The rest sit behind their own
        # SEE MORE, as the live page pages them.
        shown = 9 if len(items) >= 9 else (len(items) - len(items) % 3 or len(items))
        first, rest = items[:shown], items[shown:]
        more = ""
        if rest:
            more = """
          <details class="gp-more">
            <summary class="gp-more__btn">See more</summary>
            <div class="gp-presslist mt-4">
%s
            </div>
          </details>""" % "\n".join(card(*c) for c in rest)
        panels.append("""        <div class="gp-panel%s" id="panel-y%s" role="tabpanel" aria-labelledby="tab-y%s"%s>
          <div class="gp-presslist">
%s
          </div>%s
        </div>""" % (" is-on" if n == 0 else "", y, y, "" if n == 0 else " hidden",
                     "\n".join(card(*c) for c in first), more))

    body += """
  <!-- ============================================================= press -->
  <!-- DATA: all %d cards, read by clicking SEE MORE until it was gone
       (crawl/prod_interact.js, %s). Order is theirs; the year tabs come
       from each card's own date line. corporate-bonds' folder tabs and blog
       card, driven by the shared _tabs.js. Their first two cards carry each
       other's descriptions; reproduced as captured. -->
  <section class="gp-section" id="press">
    <div class="gp-shell">
      <div class="gp-tabs mb-6">
        <div class="gp-tabs__track" role="tablist" aria-label="Year">
          <span class="gp-tabs__ink" aria-hidden="true"></span>
%s
        </div>
      </div>
%s
    </div>
  </section>
""" % (len(cards), SNAPSHOT, tabs, "\n".join(panels))
    tabs_js = "<script>\n%s</script>\n" % open(os.path.join(HERE, "_tabs.js"), encoding="utf-8").read()
    page("media", "Media | GoldenPi", "Goldenpi media",
         "Media, rebuilt from goldenpi.com/media on corporate-bonds.html's components.", body, tabs_js)


