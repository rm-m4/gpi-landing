def reviews(slug):
    """The five Google reviews, verbatim from the capture, in corporate-bonds'
    drifting row."""
    h = capture(slug)
    i = h.index("<happy-users")
    seg = h[i:h.index("</happy-users>", i)]
    cards = re.findall(r'<img class="user-img" alt="[^"]*" src="[^"]*/([^"/]+)">.*?'
                       r'<span class="user-name">(.*?)</span>.*?<span class="feedback-txt">(.*?)</span>', seg, re.S)
    seen, rows = set(), []
    for img, name, text in cards:
        name = html.unescape(name).strip()
        if name in seen:
            continue
        seen.add(name)
        rows.append((name, img, re.sub(r"\s+", " ", html.unescape(re.sub("<[^>]+>", "", text))).strip()))
    if len(rows) != 5:
        raise SystemExit("reviews: expected 5 in %s, found %d" % (slug, len(rows)))

    def fig(r, hidden=False):
        name, img, text = r
        return """          <figure class="gp-review"%s>
            <figcaption class="gp-review__head">
              <img class="gp-review__avatar gp-review__avatar--photo" src="../assets/img/%s" alt="" width="56" height="56" loading="lazy">
              <span>
                <span class="gp-review__name">%s</span>
                <span class="gp-review__stars" aria-label="5 out of 5 stars">&#9733;&#9733;&#9733;&#9733;&#9733;</span>
              </span>
            </figcaption>
            <blockquote class="gp-review__text">%s</blockquote>
          </figure>""" % (' aria-hidden="true"' if hidden else "", img, esc(name), esc(text))

    link = re.search(r'href="([^"]+)"[^>]*>Read all Reviews', seg).group(1)
    return section("""%s

      <!-- DATA: Google reviews, as production shows them on %s. -->
      <div class="gp-reviews">
        <div class="gp-reviews__track" style="--n:5">
%s
%s
        </div>
      </div>

      <div class="mt-5 text-center">
        <a class="t-small font-bold t-bronze underline" href="%s">Read all Reviews</a>
      </div>""" % (head("Why 15 Lakh+ Users Trust GoldenPi for Bond Investing"), SNAPSHOT,
                   "\n".join(fig(r) for r in rows), "\n".join(fig(r, True) for r in rows), link))


