def faq_from_capture(slug):
    h = capture(slug)
    qa = re.findall(r'<h3 class="header-title[^"]*"[^>]*>(.*?)</h3>.*?<div class="desc[^"]*">(.*?)</div>', h, re.S)
    out = []
    for q, a in qa:
        a = a.replace("<!---->", "").strip()
        paras = [p.strip() for p in re.split(r"(?:<br>\s*){2,}", a) if p.strip()]
        out.append((html.unescape(q).strip(),
                    "".join("<p>%s</p>" % p.replace("<a href=", '<a class="underline" href=') for p in paras)))
    return out


